## Code to generate `R/tz_legacy_links.R`
##
## Maps each legacy timezone name in the tz database's `backward` file, such as
## US/Eastern, to its canonical name, such as America/New_York. Run from the
## package root to regenerate it from the latest tz database release.

tmp <- tempfile()
dir.create(tmp)
tarball <- file.path(tmp, "tzdata.tar.gz")
utils::download.file(
  "https://data.iana.org/time-zones/tzdata-latest.tar.gz",
  tarball,
  quiet = TRUE
)
utils::untar(tarball, files = c("backward", "version"), exdir = tmp)

version <- readLines(file.path(tmp, "version"))
lines <- readLines(file.path(tmp, "backward"))
links <- strsplit(grep("^Link\t", lines, value = TRUE), "\t+")
target <- vapply(links, `[[`, character(1), 2L)
alias <- vapply(links, `[[`, character(1), 3L)

# A single lookup is enough only if no target is itself an alias.
stopifnot(!any(target %in% alias), !anyDuplicated(alias))
# Guards against a change in the file's format silently dropping entries.
stopifnot(
  length(alias) > 200L,
  target[alias == "US/Eastern"] == "America/New_York"
)

ord <- order(alias)
entries <- sprintf('  "%s" = "%s"', alias[ord], target[ord])

writeLines(
  c(
    sprintf(
      "# Generated by data-raw/tz_legacy_links.R from tzdata %s.",
      version
    ),
    "# Do not edit by hand.",
    "",
    "# Legacy timezone names and the canonical names they link to.",
    "tz_legacy_links <- c(",
    paste(entries, collapse = ",\n"),
    ")"
  ),
  "R/tz_legacy_links.R"
)
